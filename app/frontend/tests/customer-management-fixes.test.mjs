function crc32(bytes) {
  let crc = 0xffffffff
  for (let i = 0; i < bytes.length; i += 1) {
    crc ^= bytes[i]
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc & 1) !== 0 ? (crc >>> 1) ^ 0xedb88320 : crc >>> 1
    }
  }
  return (crc ^ 0xffffffff) >>> 0
}

/**
 * Pure binary parser for Store-mode ZIP archives generated by buildCustomersXlsxBytes.
 * Verifies EOCD, central directory signatures, local file headers, UTF-8 flag, and CRC32.
 */
function parseAndValidateZip(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  const decoder = new TextDecoder('utf-8')

  let eocdOffset = -1
  for (let i = bytes.length - 22; i >= 0; i -= 1) {
    if (view.getUint32(i, true) === 0x06054b50) {
      eocdOffset = i
      break
    }
  }
  assert.ok(eocdOffset >= 0, 'ZIP archive must contain End of Central Directory signature')

  const totalEntries = view.getUint16(eocdOffset + 10, true)
  const cdSize = view.getUint32(eocdOffset + 12, true)
  const cdOffset = view.getUint32(eocdOffset + 16, true)
  assert.equal(cdOffset + cdSize, eocdOffset, 'Central directory size + offset must align with EOCD')

  const entries = new Map()
  let cursor = cdOffset
  for (let idx = 0; idx < totalEntries; idx += 1) {
    assert.equal(view.getUint32(cursor, true), 0x02014b50, `Central header ${idx} signature`)
    const flags = view.getUint16(cursor + 8, true)
    assert.equal(flags & 0x0800, 0x0800, 'UTF-8 filename flag (0x0800) must be set')
    const compressionMethod = view.getUint16(cursor + 10, true)
    assert.equal(compressionMethod, 0, 'Store compression method (0) expected')

    const expectedCrc = view.getUint32(cursor + 16, true)
    const compressedSize = view.getUint32(cursor + 20, true)
    const uncompressedSize = view.getUint32(cursor + 24, true)
    assert.equal(compressedSize, uncompressedSize)

    const nameLen = view.getUint16(cursor + 28, true)
    const extraLen = view.getUint16(cursor + 30, true)
    const commentLen = view.getUint16(cursor + 32, true)
    const localHeaderOffset = view.getUint32(cursor + 42, true)
    const name = decoder.decode(bytes.subarray(cursor + 46, cursor + 46 + nameLen))

    assert.equal(view.getUint32(localHeaderOffset, true), 0x04034b50, `Local header signature for ${name}`)
    const localFlags = view.getUint16(localHeaderOffset + 6, true)
    assert.equal(localFlags & 0x0800, 0x0800, `Local header UTF-8 flag for ${name}`)
    const localNameLen = view.getUint16(localHeaderOffset + 26, true)
    const localExtraLen = view.getUint16(localHeaderOffset + 28, true)
    const dataStart = localHeaderOffset + 30 + localNameLen + localExtraLen
    const payload = bytes.subarray(dataStart, dataStart + uncompressedSize)

    assert.equal(crc32(payload), expectedCrc, `CRC32 mismatch for ZIP entry ${name}`)
    entries.set(name, decoder.decode(payload))

    cursor += 46 + nameLen + extraLen + commentLen
  }

  return entries
}

