    assert.ok(rows[1].includes('Nguyễn Thị Ánh Tuyết'), 'Vietnamese diacritics preserved')
    assert.ok(rows[1].includes('"Số 5, Đường ""Lê Lợi"", Quận 1"'), 'Commas and double quotes RFC4180 escaped')
    assert.ok(rows[1].includes(',Vàng,4200000,Cần theo dõi,'), 'Tier and flag label mapped accurately')
    assert.ok(rows[1].includes("'=CMD|'/C calc'!A0"), 'Leading = neutralized with apostrophe')

    assert.ok(rows[2].includes("'+SUM(A1:A2)"), 'Leading + neutralized')
    assert.ok(rows[2].includes("'-0912345678"), 'Leading - neutralized')
    assert.ok(rows[2].includes("'@HYPERLINK("), 'Leading @ neutralized')
    assert.ok(rows[2].includes("'\t=1+1"), 'Leading tab neutralized')
    assert.ok(rows[2].includes(',Thường,0,Bình thường,'), 'Lowercase tier mapped & NaN spend clamped to 0')
